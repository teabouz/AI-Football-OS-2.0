"""
Learning Academy — Phase 6.

Course/lesson STRUCTURE is curated (academy_curriculum.py); lesson CONTENT
and quizzes are generated by Claude the first time anyone opens a lesson,
then cached on the Lesson row and reused for every user after that — one
generation per lesson ever, not one per user.

Lessons and quizzes are free for everyone (matches the roadmap's own free
tier, which includes basic lessons/quizzes). Certificates — the tangible
credential for finishing a whole course — are a Premium perk, the same
freemium pattern as course platforms that let you audit free and pay for
the certificate.
"""
